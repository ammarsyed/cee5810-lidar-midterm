"""Build a one-page local "demo board" (figures/<person>/index.html) with every video and the key
figures in presentation order. Open it in a browser to present.

Run: uv run python -m experiments.demo_board [--person partner] [--open]
(run experiments.run_all first so the media exist)
"""

